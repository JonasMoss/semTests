test_that("score matrices give the quadratic and generalized spectrum", {
  s <- c(1, 2)
  H <- matrix(c(2, .3, .3, 1), 2)
  J <- matrix(c(3, .2, .2, 2), 2)
  x <- score_test_matrices(s, H, J, keep = TRUE)
  expect_s3_class(x, "semTests_test")
  expect_equal(x$statistic, drop(crossprod(s, solve(H, s))))
  expect_equal(x$eigenvalues, sort(eigen(solve(H, J))$values, decreasing = TRUE))
  expect_equal(x$p_value, pvalue_all(x$statistic, x$eigenvalues))
  expect_equal(x$ingredients$score_covariance, J)
  expect_identical(x$ingredients$units, "sum")
  expect_identical(x$rank, 2L)
  expect_equal(score_test_matrices(s, score_covariance = J)$statistic,
               drop(crossprod(s, solve(J, s))))
})

test_that("score normalization and invertible coordinate changes preserve inference", {
  s <- c(1, 2)
  H <- matrix(c(2, .3, .3, 1), 2)
  J <- matrix(c(3, .2, .2, 2), 2)
  x <- score_test_matrices(s, H, J)
  mean_input <- score_test_matrices(s / 100, H / 100, J / 100,
                                    normalization = "mean", nobs = 100, keep = TRUE)
  expect_equal(mean_input$statistic, x$statistic)
  expect_equal(mean_input$eigenvalues, x$eigenvalues)
  expect_equal(mean_input$ingredients$score, s)
  A <- matrix(c(2, .4, .1, 1), 2)
  transformed <- score_test_matrices(drop(crossprod(A, s)),
    crossprod(A, H %*% A), crossprod(A, J %*% A))
  expect_equal(transformed$statistic, x$statistic)
  expect_equal(transformed$eigenvalues, x$eigenvalues)
  # Rescaling the criterion rescales statistic and reference weights together.
  scaled <- score_test_matrices(3 * s, 3 * H, 9 * J)
  expect_equal(scaled$statistic, 3 * x$statistic)
  expect_equal(scaled$eigenvalues, 3 * x$eigenvalues)
  expect_equal(scaled$p_value, x$p_value, tolerance = 1e-8)
})

test_that("Wald uses sampling covariance and supports constrained parameter covariance", {
  theta <- c(.4, -.2, .7)
  V <- diag(c(.02, .03, 0))
  R <- rbind(c(1, -1, 0), c(0, 1, 0))
  rhs <- c(.1, -.3)
  x <- wald_test_matrices(theta, R, V, rhs, keep = TRUE)
  d <- drop(R %*% theta) - rhs
  T <- drop(crossprod(d, solve(R %*% V %*% t(R), d)))
  expect_equal(x$statistic, T)
  expect_equal(x$p_value, pchisq(T, 2, lower.tail = FALSE))
  expect_equal(x$ingredients$contrast, d)
  A <- matrix(c(2, .1, .4, 1), 2)
  changed <- wald_test_matrices(theta, A %*% R, V, drop(A %*% rhs))
  expect_equal(changed$statistic, T)
  P <- diag(c(2, 3, 4))
  changed <- wald_test_matrices(drop(P %*% theta), R %*% solve(P),
                                P %*% V %*% t(P), rhs)
  expect_equal(changed$statistic, T)
})

test_that("matrix calibrations preserve names and reject incompatible choices", {
  s <- score_test_matrices(c(1, 2), diag(2), diag(c(1, 2)))
  specs <- c("SB", "ALL", "PEBA2", "SB", "SS", "PALL", "SF", "EBA2", "POLS2")
  actual <- pvalues(s, specs)
  expect_identical(names(actual), tolower(specs))
  expect_equal(as.numeric(actual), unname(vapply(specs, function(z) as.numeric(pvalues(s, z)), numeric(1))))
  expect_equal(as.numeric(pvalues(s)), s$p_value)
  expect_equal(as.numeric(pvalues(s, "PEBA2")), peba_pvalue(s$statistic, s$eigenvalues, 2))
  expect_error(pvalues(s, "SB_ML"), "suffixes")
  expect_error(pvalues(s, "SB_UG"), "suffixes")
  expect_error(pvalues(s, "PEBA3"), "degrees of freedom")
  expect_error(pvalues(s, fiml.convention = "observed"), "does not apply")
  w <- wald_test_matrices(c(10, 10), diag(2), diag(2))
  expect_gt(as.numeric(pvalues(w)), 0) # Avoid cancellation in the far tail.
  expect_equal(as.numeric(pvalues(w)), pchisq(200, 2, lower.tail = FALSE))
  expect_error(pvalues(w, "PEBA2"), "only STD")
  expect_error(pvalues(score_test_matrices(c(1, 2), score_covariance = diag(2)), "SB"), "only STD")
})

test_that("matrix result printing, tabulation and serialization are stable", {
  x <- score_test_matrices(c(1, 2), diag(2), diag(2), keep = TRUE)
  expect_output(print(x), "score test")
  expect_output(print(pvalues(x)), "test: score")
  frame <- as.data.frame(x)
  expect_equal(frame$statistic, x$statistic)
  expect_equal(frame$reference, x$reference)
  expect_identical(unserialize(serialize(x, NULL)), x)
})

test_that("matrix kernels fail clearly for invalid or unidentified inputs", {
  expect_error(score_test_matrices(c(1, NA), diag(2), diag(2)), "finite numeric")
  expect_error(score_test_matrices(c(1, 2), diag(3), diag(2)), "2 by 2")
  expect_error(score_test_matrices(c(1, 2), matrix(c(1, 1, 0, 1), 2), diag(2)), "symmetric")
  expect_error(score_test_matrices(c(1, 2), diag(c(1, 0)), diag(2)), "positive definite")
  expect_error(score_test_matrices(c(1, 2), diag(2), diag(c(1, -1))), "positive definite")
  expect_error(score_test_matrices(1, score_covariance = matrix(1), normalization = "mean"), "nobs")
  expect_error(score_test_matrices(1, score_covariance = matrix(1), nobs = -1), "positive integer")
  expect_error(wald_test_matrices(c(1, 2), rbind(c(1, 0), c(1, 0)), diag(2)), "redundant")
  expect_error(wald_test_matrices(c(1, 2), diag(2), diag(c(1, -1))), "semidefinite")
  expect_error(wald_test_matrices(c(1, 2), diag(2), diag(2), rhs = 0), "one value")
  expect_error(wald_test_matrices(c(1, 2), diag(2), diag(2), keep = NA), "logical keep")
})
